# SOLUÇÃO - EXERCÍCIO 1: O Inventário do Alquimista (Listas)

# 1. Criando a lista inicial
inventario = ["Teclado", "Café", "Mouse"]
print("Inventário inicial:", inventario)

# 2. Adicionando fones
inventario.append("Fones de Ouvido")

# 3. Removendo o mouse
inventario.remove("Mouse")

# 4. Tamanho da lista
print(f"Meu inventário atualizado tem {len(inventario)} itens.")

# 5. Lista final
print("Lista final:", inventario)
